/** @vitest-environment jsdom */
import {createRoot} from 'solid-js'
import {afterEach, expect, it, vi} from 'vitest'
import {invoke, isTauri} from '@tauri-apps/api/core'
import {createLibraryRepository} from '@winter-love/wallpaper/settings/library-repository'
import type {CodexSpeechTarget} from '../../codex/types'
import {useSpeechDrag} from '../use-speech-drag'

vi.mock('@tauri-apps/api/core', () => ({invoke: vi.fn(), isTauri: vi.fn()}))
vi.mock('@winter-love/wallpaper/settings/library-repository', () => ({
  createLibraryRepository: vi.fn(),
}))
afterEach(() => vi.resetAllMocks())
const mount = (target: CodexSpeechTarget = {widgetHeight: 400, widgetWidth: 200, x: 0, y: 0}) => {
  vi.mocked(isTauri).mockReturnValue(true)
  vi.mocked(invoke).mockResolvedValue(undefined)
  const save = vi.fn().mockResolvedValue(undefined)
  const close = vi.fn()
  vi.mocked(createLibraryRepository).mockReturnValue({
    addWidget: vi.fn(),
    bindWidget: vi.fn(),
    close,
    configureConnections: vi.fn(),
    configureSpeech: vi.fn(),
    configureTracking: vi.fn(),
    moveSpeech: save,
    moveWidget: vi.fn(),
    read: vi.fn(),
    removeVisit: vi.fn(),
    removeWidget: vi.fn(),
    resizeWidget: vi.fn(),
    setWidgetMotion: vi.fn(),
    subscribe: vi.fn(),
    trackWidget: vi.fn(),
    visit: vi.fn(),
  })
  const handle = document.createElement('button')
  handle.dataset.speechDragHandle = ''
  handle.setPointerCapture = vi.fn()
  handle.releasePointerCapture = vi.fn()
  handle.hasPointerCapture = vi.fn(() => true)
  const scope = createRoot((dispose) => ({
    dispose,
    drag: useSpeechDrag({
      speech: () => ({enabled: true, x: 0.9, y: 0.05}),
      target: () => target,
      widgetId: () => 'widget',
    }),
  }))
  const pointer = (x: number, y: number, options: PointerEventInit = {}) => {
    const event = new MouseEvent('pointermove', {button: 0, screenX: x, screenY: y, ...options})
    Object.defineProperties(event, {pointerId: {value: 1}, target: {value: handle}})
    return event as PointerEvent
  }
  return {...scope, close, handle, pointer, save}
}

it('should preview screen deltas relative to widget size and persist once on release', async () => {
  const view = mount()
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(140, 240))
  await view.drag.finish(view.pointer(140, 240))
  expect(invoke).toHaveBeenLastCalledWith('move_poffo_speech', {anchor: 'bottom', x: 1.1, y: 0.15})
  expect(view.save).toHaveBeenCalledExactlyOnceWith('widget', {anchor: 'bottom', x: 1.1, y: 0.15})
  expect(view.close).toHaveBeenCalledOnce()
  expect(view.drag.dragging()).toBe(false)
  view.dispose()
})

it('should leave a click alone and suppress only the click generated by a completed drag', async () => {
  const view = mount()
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(101, 201))
  await view.drag.finish(view.pointer(101, 201))
  const click = new MouseEvent('click', {cancelable: true, detail: 1})
  Object.defineProperty(click, 'target', {value: view.handle})
  view.drag.click(click)
  expect(click.defaultPrevented).toBe(false)
  expect(view.save).not.toHaveBeenCalled()
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(140, 240))
  await view.drag.finish(view.pointer(140, 240))
  view.drag.click(click)
  expect(click.defaultPrevented).toBe(true)
  const unrelated = new MouseEvent('click', {cancelable: true, detail: 1})
  Object.defineProperty(unrelated, 'target', {value: document.createElement('button')})
  view.drag.click(unrelated)
  expect(unrelated.defaultPrevented).toBe(false)
  view.dispose()
})

it('should restore the original position on Escape without persisting a cancelled drag', async () => {
  const view = mount()
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(140, 240))
  view.drag.keyboard(new KeyboardEvent('keydown', {key: 'Escape'}))
  await vi.waitFor(() =>
    expect(invoke).toHaveBeenLastCalledWith('move_poffo_speech', {
      anchor: undefined,
      x: 0.9,
      y: 0.05,
    }),
  )
  expect(view.save).not.toHaveBeenCalled()
  expect(view.drag.dragging()).toBe(false)
  view.dispose()
})

it('should coalesce pending previews and wait for the final placement before saving', async () => {
  const view = mount()
  const first = Promise.withResolvers<void>()
  vi.mocked(invoke).mockReturnValueOnce(first.promise)
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(120, 220))
  view.drag.move(view.pointer(140, 240))
  view.drag.move(view.pointer(160, 260))
  const finished = view.drag.finish(view.pointer(160, 260))
  expect(invoke).toHaveBeenCalledTimes(1)
  expect(view.save).not.toHaveBeenCalled()
  first.resolve()
  await finished
  expect(invoke).toHaveBeenCalledTimes(2)
  expect(view.save).toHaveBeenCalledExactlyOnceWith('widget', {anchor: 'bottom', x: 1.2, y: 0.2})
  view.dispose()
})

it('should restore placement and expose a save failure', async () => {
  const view = mount()
  view.save.mockRejectedValue(new Error('storage unavailable'))
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(140, 240))
  await view.drag.finish(view.pointer(140, 240))
  expect(view.drag.error()).toBe('말풍선 위치를 저장하지 못했어요.')
  expect(invoke).toHaveBeenLastCalledWith('move_poffo_speech', {anchor: undefined, x: 0.9, y: 0.05})
  expect(view.close).toHaveBeenCalledOnce()
  view.dispose()
})

it('should constrain movement and include the final pointer position', async () => {
  const view = mount()
  view.drag.start(view.pointer(100, 200))
  view.drag.move(view.pointer(120, 220))
  await view.drag.finish(view.pointer(2100, -1800))
  expect(view.save).toHaveBeenCalledExactlyOnceWith('widget', {anchor: 'bottom', x: 2, y: -0.5})
  view.dispose()
})

it('should start dragging from the rendered attachment after automatic placement', async () => {
  const view = mount({
    anchor: 'top',
    positionX: 0.5,
    positionY: 1,
    widgetHeight: 400,
    widgetWidth: 200,
    x: 0,
    y: 0,
  })
  view.drag.start(view.pointer(100, 200))
  await view.drag.finish(view.pointer(140, 240))
  expect(view.save).toHaveBeenCalledExactlyOnceWith('widget', {anchor: 'top', x: 0.7, y: 1.1})
  view.dispose()
})
